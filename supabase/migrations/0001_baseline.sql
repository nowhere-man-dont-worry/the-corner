-- ------------------------------------------------------------------ places
create table public.places (
  id uuid primary key default gen_random_uuid(),
  category text not null check (category in ('food','admin','nightlife','student-resources')),
  name text not null check (char_length(name) between 1 and 80),
  address text check (address is null or char_length(address) <= 200),
  tip text check (tip is null or char_length(tip) <= 400),
  lat double precision check (lat is null or lat between -90 and 90),
  long double precision check (long is null or long between -180 and 180),
  submitted_by uuid references auth.users(id) on delete set null,
  submitted_handle text,
  created_at timestamptz default now()
);
alter table public.places enable row level security;
create policy "places readable by all" on public.places for select using (true);
create policy "signed-in users add places" on public.places for insert to authenticated with check (submitted_by = auth.uid());

-- ---------------------------------------------------------------- triggers
-- Handles and names always come from the GitHub identity, never the client.
create or replace function public.messages_set_name() returns trigger
language plpgsql security definer set search_path = '' as $$
declare dn text; gh text;
begin
  select i.identity_data->>'user_name' into gh from auth.identities i
   where i.user_id = new.user_id and i.provider = 'github' limit 1;
  if gh is null then raise exception 'no github identity for this user'; end if;
  select nullif(btrim(p.display_name), '') into dn from public.profiles p where p.user_id = new.user_id;
  if dn is null then new.name := '@' || gh;
  else new.name := rtrim(left(dn, 60 - char_length(gh) - 4)) || ' · @' || gh;
  end if;
  return new;
end $$;
create trigger messages_name_trigger before insert on public.messages
  for each row execute function public.messages_set_name();

create or replace function public.profiles_set_handle() returns trigger
language plpgsql security definer set search_path = '' as $$
declare gh text;
begin
  select i.identity_data->>'user_name' into gh from auth.identities i
   where i.user_id = new.user_id and i.provider = 'github' limit 1;
  if gh is null then raise exception 'no github identity for this user'; end if;
  new.handle := gh;
  return new;
end $$;
create trigger profiles_lock_handle before insert or update on public.profiles
  for each row execute function public.profiles_set_handle();

create or replace function public.profiles_set_updated() returns trigger
language plpgsql as $$ begin new.updated_at := now(); return new; end $$;
create trigger profiles_touch_updated_at before update on public.profiles
  for each row execute function public.profiles_set_updated();

create or replace function public.places_sign() returns trigger
language plpgsql security definer set search_path = '' as $$
declare gh text;
begin
  if auth.uid() is null then raise exception 'sign in to add a spot'; end if;
  select i.identity_data->>'user_name' into gh from auth.identities i
   where i.user_id = auth.uid() and i.provider = 'github' limit 1;
  if gh is null then raise exception 'no github identity for this user'; end if;
  new.id := gen_random_uuid();
  new.submitted_by := auth.uid();
  new.submitted_handle := gh;
  new.created_at := now();
  return new;
end $$;
create trigger places_sign_insert before insert on public.places
  for each row execute function public.places_sign();

