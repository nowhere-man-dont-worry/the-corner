-- ---------------------------------------------------------------- messages
create table public.messages (
  id bigint generated by default as identity primary key,
  room text not null,
  name text not null,
  avatar jsonb not null,
  text text not null,
  created_at timestamptz default now(),
  user_id uuid not null references auth.users(id),
  constraint msg_room_ok check (room in ('plaza','council','suggestions','events','guide','members')),
  constraint msg_name_len check (char_length(name) between 1 and 60),
  constraint msg_text_len check (char_length(text) between 1 and 200),
  constraint msg_avatar_ok check (
    (avatar->>'hair') in ('buzz','mop','long','bun','curls','cap')
    and (avatar->>'hairColor') ~ '^#[0-9a-fA-F]{6}$'
    and (avatar->>'skin') ~ '^#[0-9a-fA-F]{6}$'
    and (avatar->>'top') ~ '^#[0-9a-fA-F]{6}$'
    and (avatar->>'bottom') ~ '^#[0-9a-fA-F]{6}$')
);
alter table public.messages enable row level security;
create policy "anyone can read" on public.messages for select using (true);
create policy "auth users insert own" on public.messages for insert with check (auth.uid() = user_id);

